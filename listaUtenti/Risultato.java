package dev.chris;

import java.util.ArrayList;
import java.util.List;

public class Risultato {

	private String risult;
	private List<String> utenti;
	
	public Risultato() {
		utenti = new ArrayList<String>();
	}
	
	public String getRisult() {
		return risult;
	}
	public void setRisult(String risult) {
		this.risult = risult;
	}
	public List<String> getUtenti() {
		return utenti;
	}
	public void setUtenti(List<String> utenti) {
		this.utenti = utenti;
	}
	
	
	
	

	
	
	
	
	
}
